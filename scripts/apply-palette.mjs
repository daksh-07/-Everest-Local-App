// Writes lib/theme-colors.ts from a palette in scripts/palette-candidates.mjs.
// Usage: node scripts/apply-palette.mjs electric   (used to build identical comparison captures)
import fs from 'node:fs';
const {candidates}=await import('./palette-candidates.mjs');
const name=process.argv[2]||'electric';
const palette=candidates[name];
if(!palette)throw new Error(`Unknown palette "${name}". Choose one of: ${Object.keys(candidates).join(', ')}`);
const keys=Object.keys(palette.light);
for(const key of keys)if(!(key in palette.dark))throw new Error(`dark palette is missing ${key}`);
const line=obj=>'{'+keys.map(k=>`${k}:'${obj[k]}'`).join(',')+'}';
const out=`// Generated by scripts/apply-palette.mjs from scripts/palette-candidates.mjs (${palette.name}).
// Edit the candidate there and re-run the script; tests/palette-contrast.test.mjs verifies every pairing.
//
// Roles
// - primary / onPrimary: filled primary actions, selected navigation. primaryText: primary as text and icons.
// - primaryContainer / onPrimaryContainer: selected chips, highlighted rows, tinted callouts.
// - secondary (+Text, container): Everest Live and selected feature highlights.
// - tertiary (+container): occasional discovery, social and shopping highlights. Never used for errors.
// - success, warning, danger, info (+container): truthful status only, always paired with text or an icon.
// - border is decorative; borderStrong meets 3:1 for control boundaries; focus meets 3:1 on canvas and surface.
// - Legacy keys: brand = primary, onBrand = onPrimary, accent = primaryText, accentSoft = primaryContainer.
export type ThemeColors={${keys.map(k=>`${k}:string`).join(';')}};
export const light:ThemeColors=${line(palette.light)};
export const dark:ThemeColors=${line(palette.dark)};
export const paletteName='${palette.name}';
`;
fs.writeFileSync(new URL('../lib/theme-colors.ts',import.meta.url),out);
console.log(`lib/theme-colors.ts ← ${palette.name} (${keys.length} roles)`);
